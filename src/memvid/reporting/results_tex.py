"""LaTeX tables of the Stage 2-5 results (report/generated/results_*.tex, perception_*.tex)."""

from __future__ import annotations

import math
from typing import Any

from memvid.config import ProjectConfig
from memvid.io import atomic_write_text
from memvid.manifest import load_manifest
from memvid.questions.manage import _frozen_info
from memvid.reporting.tex import kv_table, tex_escape

HEADER = "% Generated by `memvid analyze` / `memvid export-tex`. Do not edit.\n"


def _ci(d: dict[str, float] | None) -> str:
    if not d or d.get("mean") is None or math.isnan(d["mean"]):
        return "--"
    return f"{d['mean']:.2f} [{d['lo']:.2f}, {d['hi']:.2f}]"


def _f(x, digits=2) -> str:
    if x is None or (isinstance(x, float) and math.isnan(x)):
        return "--"
    if isinstance(x, float):
        return f"{x:.{digits}f}"
    return tex_escape(x)


def _table(caption: str, label: str, header: list[str], rows: list[list[str]], size: str = "small") -> str:
    align = "l" + "c" * (len(header) - 1)
    body = "\n".join(" & ".join(r) + r" \\" for r in rows)
    tight = "\\setlength{\\tabcolsep}{3pt}" if size != "small" else ""
    return (HEADER + f"\\begin{{table}}[ht]\n\\centering\\{size}{tight}\n"
            f"\\caption{{{caption}}}\\label{{{label}}}\n"
            f"\\begin{{tabular}}{{@{{}}{align}@{{}}}}\n\\toprule\n" + " & ".join(header) + r" \\" +
            "\n\\midrule\n" + body + "\n\\bottomrule\n\\end{tabular}\n\\end{table}\n")


def export_results(cfg: ProjectConfig, summary: dict[str, Any], budgets: list[str]) -> None:
    out = cfg.report_generated_dir
    out.mkdir(parents=True, exist_ok=True)
    runs = summary["runs"]
    note = (r" \textbf{Heuristic stand-in models: numbers are not valid results.}"
            if summary.get("heuristic_models") else "")

    def run(c, b):
        return runs.get(f"{c}_{b}")

    # accuracy x budget
    rows = []
    for c in ("C1", "C2", "C3"):
        rows.append([c] + [_ci((run(c, b) or {}).get("accuracy")) for b in budgets])
    c4 = run("C4", "full")
    rows.append(["C4 (unbounded)"] + [_ci(c4["accuracy"]) if c4 else "--"] + ["" for _ in budgets[1:]])
    tok = summary["budgets_tokens"]
    header = ["Condition"] + [f"{b} ({tok.get(b, '?')} tok.)" for b in budgets]
    atomic_write_text(out / "results_accuracy.tex", _table(
        f"Answer accuracy with 95\\% bootstrap intervals, {summary['n_questions']} "
        f"{summary['split']} questions.{note}", "tab:results-accuracy", header, rows))

    # by type at focus budget
    focus = cfg.experiment.ablation_budget
    types = sorted({t for r in runs.values() for t in r["by_type"]})
    conds = [("C1", focus), ("C2", focus), ("C3", focus), ("C4", "full")]
    trows = [[tex_escape(t.replace("_", " "))] + [_ci((run(c, b) or {}).get("by_type", {}).get(t))
                                                 for c, b in conds] for t in types]
    atomic_write_text(out / "results_by_type.tex", _table(
        f"Accuracy by question type at budget {focus} (C4 unbounded).{note}", "tab:results-type",
        ["Type", "C1", "C2", "C3", "C4"], trows))

    # grounding / retrieval / survival
    grows = []
    for c, b in [("C2", focus), ("C3", focus), ("C4", "full")]:
        r = run(c, b)
        if r:
            grows.append([c, _ci(r["survived"]), _ci(r["retrieved"]), _ci(r["grounded"]),
                          _ci(r.get("g_precision")), _ci(r["tiou"])])
    atomic_write_text(out / "results_grounding.tex", _table(
        f"Evidence coverage (survival proxy), retrieval recall and grounding at budget {focus}.{note}",
        "tab:results-grounding", ["Condition", "Survived", "Retrieved", "Grounded", "Precision", "tIoU"],
        grows))

    # ablations
    arows = []
    for name in ["C3", *[f"C3-{a}" for a in cfg.experiment.ablations]]:
        r = run(name, focus)
        if r:
            arows.append([tex_escape(name), _ci(r["accuracy"]), _ci(r["survived"]), _ci(r["grounded"])])
    atomic_write_text(out / "results_ablations.tex", _table(
        f"Ablations of the structured memory at budget {focus}.{note}", "tab:results-ablations",
        ["Variant", "Accuracy", "Survived", "Grounded"], arows))

    # how memory was updated (operation log)
    ops = summary.get("operations", {})
    if ops:
        orow = []
        for name in sorted(ops):
            o = ops[name]
            fr = o["final_records"]
            orow.append([tex_escape(name), *(str(o["ops"].get(k, 0)) for k in
                         ("insert", "link", "change", "extend", "rewrite", "compress", "evict")),
                         str(o["compressed_away"]),
                         f"{fr.get('entity', 0)}/{fr.get('event', 0)}/{fr.get('state_change', 0)}/"
                         f"{fr.get('relation', 0)}/{fr.get('note', 0)}"])
        atomic_write_text(out / "results_operations.tex", _table(
            "How each memory was updated: operations in the log (rewrite = C1 summary updates, "
            "compress = summaries written, merged = originals replaced by them) and final records "
            "(entities/events/state changes/relations/notes).",
            "tab:results-operations",
            ["Run", "Insert", "Link", "Change", "Extend", "Rewrite", "Compress", "Evict", "Merged",
             "E/V/S/R/N"], orow, size="footnotesize"))

    # McNemar
    mrows = [[m["budget"], m["comparison"], str(m["only_C3"]), str(m["only_other"]), str(m["n"]),
              _f(m["p"], 3)] for m in summary["mcnemar"]]
    atomic_write_text(out / "results_mcnemar.tex", _table(
        "Paired comparisons (exact McNemar test; discordant pairs).", "tab:results-mcnemar",
        ["Budget", "Comparison", "Only C3", "Only other", "n", "p"], mrows))

    # attribution
    by_run = summary["attribution"]["by_run"]
    causes = ["perception_miss", "storage_loss", "corruption_merge", "corruption_state",
              "retrieval_miss", "reasoning_error"]
    atrows = [[tex_escape(r)] + [str(by_run[r].get(c, 0)) for c in causes] for r in sorted(by_run)]
    atomic_write_text(out / "results_attribution.tex", _table(
        "Failure attribution: wrong answers by the first stage where the evidence was lost.",
        "tab:results-attribution", ["Run", "Perc.", "Storage", "Merge", "State", "Retr.", "Reason."],
        atrows))
    export_stage_tables(cfg)


def export_stage_tables(cfg: ProjectConfig) -> None:
    """Questions, perception and audit statistics from the manifest and audit summaries."""
    out = cfg.report_generated_dir
    m = load_manifest(cfg.derived_dir, cfg.video.video_id)
    q = _frozen_info(m, cfg.questions.filename)
    if q:
        rows = [("Questions (dev / test)", f"{q['n_questions']} ({q['n_dev']} / {q['n_test']})")]
        rows += [(f"  {t.replace('_', ' ')}", n) for t, n in q["by_type"].items()]
        atomic_write_text(out / "questions_stats.tex", HEADER + kv_table(
            rows, "Evaluation set (generated from the manifest).", "tab:questions"))
    p = m.stats.get("perception")
    if p:
        rows = [("Model", p.get("model")), ("Prompt version", p.get("prompt_version")),
                ("Pixel budget per frame", p.get("max_pixels")), ("Chunks", p["n_chunks"]),
                ("Parse failures (rate)", f"{p['parse_failures']} ({p['parse_failure_rate']:.3f})"),
                ("Repaired by retry", p["repaired"]),
                ("Mean entities / events / relations per chunk",
                 f"{p['mean_entities']} / {p['mean_events']} / {p['mean_relations']}"),
                ("Dropped references", p["dropped_refs"])]
        a = m.stats.get("perception_audit")
        if a:
            rows += [("Audited chunks", a["n_chunks"]), ("False-entity rate", a["false_entity_rate"]),
                     ("Missed-salient-event rate", a["missed_event_rate"]),
                     ("Audit accepted", a["accepted"])]
        atomic_write_text(out / "perception_stats.tex", HEADER + kv_table(
            rows, "Perception statistics (generated from the manifest).", "tab:perception"))
    from memvid.evaluation.audits import audits_dir
    from memvid.io import read_json

    rows = []
    for name, keys in (("merge_audit_summary.json", [("Merge precision", "merge_precision"),
                                                     ("Missed-merge rate", "missed_merge_rate")]),
                       ("state_audit_summary.json", [("State-change precision", "precision")]),
                       ("judge_audit_summary.json", [("LLM-judge agreement", "agreement")])):
        f = audits_dir(cfg) / name
        if f.is_file():
            d = read_json(f)
            for label, k in keys:
                ci, v = d.get(f"{k}_ci"), d.get(k)
                rows.append((label, "--" if v is None else
                             f"{v:.2f} [{ci[0]:.2f}, {ci[1]:.2f}]" if ci else f"{v:.2f}"))
    if rows:
        atomic_write_text(out / "audit_stats.tex", HEADER + kv_table(
            rows, "Manual audits with 95\\% Wilson intervals.", "tab:audits"))
